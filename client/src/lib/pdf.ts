import type { jsPDF } from 'jspdf';
import { paperColor } from './colors';
import { addMinutes, fmtDate, fmtDuration, fmtTime } from './format';
import { buildSeats, circularPosition } from './layout';
import type { Duty, Paper, PlanDetail, PlanRoom, SeatAssignment, TeacherDuty } from './types';

export interface Letterhead {
  institution_name: string;
  institution_address?: string;
  exam_cell_name: string;
  controller_name?: string;
}

const naturalCompare = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' }).compare;
const SLATE = [15, 23, 42] as const;
const MUTED = [100, 116, 139] as const;
const LINE = [203, 213, 225] as const;
const INDIGO = [79, 70, 229] as const;

async function newDoc(orientation: 'portrait' | 'landscape') {
  const [{ jsPDF }, autoTable] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const doc = new jsPDF({ orientation, unit: 'mm', format: 'a4' });
  doc.setFont('helvetica', 'normal');
  return { doc, autoTable: autoTable.default };
}

function hexToRgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

const ascii = (s: string | null | undefined) =>
  String(s ?? '')
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/·/g, '|');

function letterhead(doc: jsPDF, lh: Letterhead, title: string, lines: string[]) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...INDIGO);
  doc.rect(0, 0, w, 2.2, 'F');
  doc.setTextColor(...SLATE);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(ascii(lh.institution_name), w / 2, 12, { align: 'center' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(...MUTED);
  const sub = [lh.exam_cell_name, lh.institution_address].filter(Boolean).map(ascii).join('  |  ');
  doc.text(sub, w / 2, 16.5, { align: 'center' });
  doc.setDrawColor(...LINE);
  doc.setLineWidth(0.3);
  doc.line(12, 19.5, w - 12, 19.5);
  doc.setTextColor(...SLATE);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text(ascii(title), 12, 26.5);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...MUTED);
  lines.forEach((l, i) => doc.text(ascii(l), 12, 31.5 + i * 4.4));
  doc.setTextColor(...SLATE);
  return 31.5 + lines.length * 4.4 + 1;
}

function footers(doc: jsPDF) {
  const pages = doc.getNumberOfPages();
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  const stamp = new Date().toLocaleString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' });
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(7.5);
    doc.setTextColor(...MUTED);
    doc.text(`Generated by ExamFlow on ${stamp}`, 12, h - 6);
    doc.text(`Page ${i} of ${pages}`, w - 12, h - 6, { align: 'right' });
  }
}

const slotLine = (d: PlanDetail) =>
  `${d.slot.exam_name}  |  ${fmtDate(d.slot.date, 'long')}  |  ${fmtTime(d.slot.start_time)} - ${fmtTime(d.slot.end_time)} (${fmtDuration(d.slot.duration_min)})`;

const roomLine = (r: PlanRoom) => [r.name, r.building, r.floor && `${r.floor} floor`].filter(Boolean).join(', ');

function roomSeats(d: PlanDetail, roomId: number) {
  return d.seats.filter((s) => s.room_id === roomId);
}

/** Roll-number ranges of a paper within a room, compressed against the paper's full sorted list. */
export function rollRanges(d: PlanDetail, roomId: number, paperId: number) {
  const all = d.seats.filter((s) => s.paper_id === paperId).map((s) => s.roll_no).sort(naturalCompare);
  const index = new Map(all.map((r, i) => [r, i]));
  const mine = d.seats
    .filter((s) => s.room_id === roomId && s.paper_id === paperId)
    .map((s) => s.roll_no)
    .sort(naturalCompare);
  const ranges: string[] = [];
  let start = 0;
  for (let i = 1; i <= mine.length; i++) {
    if (i === mine.length || index.get(mine[i])! !== index.get(mine[i - 1])! + 1) {
      ranges.push(i - 1 === start ? mine[start] : `${mine[start]} - ${mine[i - 1]}`);
      start = i;
    }
  }
  return { ranges, count: mine.length };
}

const paperName = (p?: Paper) => (p ? `${p.short}${p.subject ? ` (${p.subject})` : ''}` : '');

/* ------------------------------------------------------------ seating chart */

function drawRoomChart(doc: jsPDF, d: PlanDetail, room: PlanRoom, lh: Letterhead) {
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const top = letterhead(doc, lh, `Seating Chart - ${roomLine(room)}`, [slotLine(d)]);
  const bySeat = new Map(roomSeats(d, room.id).map((s) => [`${s.r}-${s.c}`, s]));
  const paperById = new Map(d.slot.papers.map((p) => [p.id, p]));
  const seats = buildSeats(room.layout, room.blocked);
  const labelOf = new Map(seats.map((s) => [s.key, s.label]));
  const blocked = new Set(room.blocked);
  const duties = d.duties.filter((x) => x.room_id === room.id);

  const legendH = 8 + Math.ceil(d.slot.papers.length / 3) * 5;
  const footH = 26;
  const areaTop = top + 9;
  const areaH = H - areaTop - legendH - footH;
  const areaW = W - 24;
  const { rows, cols } = room.layout;

  const drawCell = (x: number, y: number, w: number, h: number, key: string) => {
    const s = bySeat.get(key);
    const label = labelOf.get(key);
    if (blocked.has(key) || !label) {
      doc.setDrawColor(...LINE);
      doc.setLineDashPattern([0.8, 0.8], 0);
      doc.rect(x, y, w, h);
      doc.setLineDashPattern([], 0);
      doc.setFontSize(6);
      doc.setTextColor(...MUTED);
      doc.text('x', x + w / 2, y + h / 2 + 1, { align: 'center' });
      return;
    }
    if (s) {
      const p = paperById.get(s.paper_id);
      const col = paperColor(p?.color ?? 0);
      doc.setFillColor(...hexToRgb(col.tint));
      doc.setDrawColor(...hexToRgb(col.hex));
      doc.setLineWidth(0.25);
      doc.roundedRect(x, y, w, h, 1, 1, 'FD');
      doc.setFillColor(...hexToRgb(col.hex));
      doc.rect(x, y + 0.6, 0.9, h - 1.2, 'F');
    } else {
      doc.setDrawColor(...LINE);
      doc.setLineWidth(0.25);
      doc.roundedRect(x, y, w, h, 1, 1, 'S');
    }
    const fs = Math.max(4.5, Math.min(7.5, w * 0.26));
    doc.setFontSize(fs * 0.75);
    doc.setTextColor(...MUTED);
    doc.text(label, x + 1.6, y + fs * 0.42);
    if (s) {
      const p = paperById.get(s.paper_id);
      doc.setTextColor(...SLATE);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(fs);
      doc.text(s.roll_no, x + w / 2, y + h / 2 + fs * 0.18, { align: 'center', maxWidth: w - 1.5 });
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(fs * 0.72);
      doc.setTextColor(...MUTED);
      doc.text(p?.short || '', x + w / 2, y + h - 1.2, { align: 'center', maxWidth: w - 1.5 });
    } else {
      doc.setFontSize(fs * 0.7);
      doc.setTextColor(...MUTED);
      doc.text('empty', x + w / 2, y + h / 2 + 1, { align: 'center' });
    }
  };

  if (room.layout.kind === 'circular') {
    const size = Math.min(areaW, areaH);
    const cellW = Math.min(22, (Math.PI * size * 0.45) / cols - 1.5);
    const cellH = cellW * 0.62;
    const R = size / 2 - cellW / 2 - 1;
    const cx = W / 2;
    const cy = areaTop + areaH / 2;
    doc.setDrawColor(...LINE);
    doc.setLineDashPattern([1, 1], 0);
    doc.circle(cx, cy, R * 0.3);
    doc.setLineDashPattern([], 0);
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text('CENTRE', cx, cy + 1, { align: 'center' });
    for (let r = 0; r < rows; r++)
      for (let c = 0; c < cols; c++) {
        const p = circularPosition(r, c, rows, cols);
        drawCell(cx + p.x * R - cellW / 2, cy + p.y * R - cellH / 2, cellW, cellH, `${r}-${c}`);
      }
  } else {
    const gap = 1.6;
    const cellW = Math.min(30, (areaW - 8 - gap * (cols - 1)) / cols);
    const cellH = Math.min(16, (areaH - gap * (rows - 1)) / rows, cellW * 0.75);
    const gridW = cols * cellW + (cols - 1) * gap;
    const x0 = (W - gridW) / 2 + 3;
    // front bar
    doc.setFillColor(241, 245, 249);
    doc.roundedRect(x0, areaTop - 7.5, gridW, 5, 1, 1, 'F');
    doc.setFontSize(7);
    doc.setTextColor(...MUTED);
    doc.text('FRONT  |  BOARD', x0 + gridW / 2, areaTop - 4.1, { align: 'center' });
    for (let r = 0; r < rows; r++) {
      doc.setFontSize(7);
      doc.setTextColor(...MUTED);
      doc.text(String.fromCharCode(65 + (r % 26)), x0 - 3, areaTop + r * (cellH + gap) + cellH / 2 + 1, { align: 'center' });
      for (let c = 0; c < cols; c++) drawCell(x0 + c * (cellW + gap), areaTop + r * (cellH + gap), cellW, cellH, `${r}-${c}`);
    }
  }

  // legend
  let ly = H - footH - legendH + 4;
  doc.setFontSize(8);
  doc.setTextColor(...SLATE);
  doc.setFont('helvetica', 'bold');
  doc.text(`Students: ${bySeat.size} / ${room.capacity} seats`, 12, ly);
  doc.setFont('helvetica', 'normal');
  ly += 4.5;
  const papersHere = d.slot.papers.filter((p) => roomSeats(d, room.id).some((s) => s.paper_id === p.id));
  papersHere.forEach((p, i) => {
    const x = 12 + (i % 3) * ((W - 24) / 3);
    const y = ly + Math.floor(i / 3) * 5;
    doc.setFillColor(...hexToRgb(paperColor(p.color).hex));
    doc.rect(x, y - 2.6, 3, 3, 'F');
    const { ranges, count } = rollRanges(d, room.id, p.id);
    doc.setTextColor(...SLATE);
    doc.text(ascii(`${paperName(p)} - ${count}  [${ranges.slice(0, 2).join(', ')}${ranges.length > 2 ? ', ...' : ''}]`), x + 4.5, y, { maxWidth: (W - 24) / 3 - 6 });
  });

  // invigilator signatures
  const fy = H - footH + 4;
  doc.setDrawColor(...LINE);
  doc.line(12, fy - 3, W - 12, fy - 3);
  doc.setFontSize(8);
  const slotsW = (W - 24) / Math.max(2, duties.length);
  (duties.length ? duties : [null, null]).forEach((t: Duty | null, i) => {
    const x = 12 + i * slotsW;
    doc.setTextColor(...MUTED);
    doc.text('Invigilator', x, fy + 1);
    doc.setTextColor(...SLATE);
    doc.text(ascii(t ? t.name : '______________________'), x, fy + 5.5);
    doc.setTextColor(...MUTED);
    doc.text('Signature: ________________', x, fy + 10);
  });
}

export async function seatingChartsPdf(d: PlanDetail, lh: Letterhead, roomIds?: number[]) {
  const { doc } = await newDoc('landscape');
  const rooms = d.rooms.filter((r) => r.assigned > 0 && (!roomIds || roomIds.includes(r.id)));
  rooms.forEach((room, i) => {
    if (i) doc.addPage();
    drawRoomChart(doc, d, room, lh);
  });
  footers(doc);
  doc.save(`seating-charts-${d.slot.date}-${d.slot.start_time.replace(':', '')}.pdf`);
}

/* ---------------------------------------------------- attendance / lists */

function seatOrder(room: PlanRoom) {
  return new Map(room.seats.map((s) => [s.key, s]));
}

export async function attendanceSheetsPdf(d: PlanDetail, lh: Letterhead, roomIds?: number[]) {
  const { doc, autoTable } = await newDoc('portrait');
  const paperById = new Map(d.slot.papers.map((p) => [p.id, p]));
  const rooms = d.rooms.filter((r) => r.assigned > 0 && (!roomIds || roomIds.includes(r.id)));
  rooms.forEach((room, i) => {
    if (i) doc.addPage();
    const top = letterhead(doc, lh, `Attendance Sheet - ${roomLine(room)}`, [slotLine(d), `Invigilator(s): ${d.duties.filter((x) => x.room_id === room.id).map((x) => x.name).join(', ') || '-'}`]);
    const order = seatOrder(room);
    const rows = roomSeats(d, room.id)
      .map((s) => ({ s, seat: order.get(`${s.r}-${s.c}`) }))
      .sort((a, b) => (a.seat?.order ?? 0) - (b.seat?.order ?? 0))
      .map(({ s, seat }, idx) => [idx + 1, seat?.label ?? '', s.roll_no, ascii(s.name), paperById.get(s.paper_id)?.short ?? '', '', '']);
    autoTable(doc, {
      startY: top + 2,
      head: [['#', 'Seat', 'Roll No.', 'Student name', 'Paper', 'Answer booklet no.', 'Signature']],
      body: rows,
      theme: 'grid',
      styles: { fontSize: 8.5, cellPadding: 1.8, lineColor: [226, 232, 240], textColor: [15, 23, 42], minCellHeight: 7 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: 'bold' },
      columnStyles: { 0: { cellWidth: 9 }, 1: { cellWidth: 13 }, 2: { cellWidth: 33, fontStyle: 'bold' }, 4: { cellWidth: 25 }, 5: { cellWidth: 26 }, 6: { cellWidth: 30 } },
      margin: { left: 12, right: 12, bottom: 16 },
    });
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    let y = ((doc as any).lastAutoTable?.finalY ?? top) + 10;
    if (y > doc.internal.pageSize.getHeight() - 30) {
      doc.addPage();
      y = 20;
    }
    doc.setFontSize(9);
    doc.text(`Total students: ${rows.length}     Present: ________     Absent: ________`, 12, y);
    doc.text('Invigilator signature: ______________________', 12, y + 9);
    doc.text('Chief superintendent: ______________________', 110, y + 9);
  });
  footers(doc);
  doc.save(`attendance-sheets-${d.slot.date}-${d.slot.start_time.replace(':', '')}.pdf`);
}

export async function noticeBoardPdf(d: PlanDetail, lh: Letterhead) {
  const { doc, autoTable } = await newDoc('portrait');
  const top = letterhead(doc, lh, 'Seating Arrangement - Notice', [slotLine(d), 'Students must carry their ID card and be seated 15 minutes before the exam begins.']);
  const body: (string | number)[][] = [];
  for (const room of d.rooms.filter((r) => r.assigned > 0)) {
    const papersHere = d.slot.papers.filter((p) => roomSeats(d, room.id).some((s) => s.paper_id === p.id));
    papersHere.forEach((p, i) => {
      const { ranges, count } = rollRanges(d, room.id, p.id);
      body.push([i === 0 ? room.name : '', i === 0 ? ascii([room.building, room.floor].filter(Boolean).join(', ')) : '', ascii(paperName(p)), ranges.join(', '), count]);
    });
  }
  autoTable(doc, {
    startY: top + 2,
    head: [['Room', 'Location', 'Paper', 'Roll numbers', 'Count']],
    body,
    theme: 'striped',
    styles: { fontSize: 9, cellPadding: 2.4, textColor: [15, 23, 42] },
    headStyles: { fillColor: [79, 70, 229], textColor: 255 },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 26 }, 1: { cellWidth: 38 }, 4: { halign: 'right', cellWidth: 16 } },
    margin: { left: 12, right: 12, bottom: 16 },
  });
  footers(doc);
  doc.save(`notice-board-${d.slot.date}-${d.slot.start_time.replace(':', '')}.pdf`);
}

export async function dutyListPdf(d: PlanDetail, lh: Letterhead) {
  const { doc, autoTable } = await newDoc('portrait');
  const report = addMinutes(d.slot.start_time, -20);
  const top = letterhead(doc, lh, 'Invigilation Duty List', [slotLine(d), `Invigilators should report to their rooms by ${fmtTime(report)}.`]);
  const roomById = new Map(d.rooms.map((r) => [r.id, r]));
  const sorted = [...d.duties].sort((a, b) => (a.role === b.role ? (roomById.get(a.room_id!)?.name || '').localeCompare(roomById.get(b.room_id!)?.name || '', undefined, { numeric: true }) : a.role === 'reserve' ? 1 : -1));
  autoTable(doc, {
    startY: top + 2,
    head: [['Room', 'Students', 'Invigilator', 'Department', 'Phone', 'Signature']],
    body: sorted.map((x) => {
      const r = x.room_id ? roomById.get(x.room_id) : null;
      return [r ? r.name : 'Reserve', r ? r.assigned : '-', ascii(x.name), ascii(x.department || ''), x.phone || '', ''];
    }),
    theme: 'grid',
    styles: { fontSize: 9, cellPadding: 2.2, lineColor: [226, 232, 240], textColor: [15, 23, 42], minCellHeight: 8 },
    headStyles: { fillColor: [79, 70, 229], textColor: 255 },
    columnStyles: { 0: { fontStyle: 'bold', cellWidth: 26 }, 1: { halign: 'right', cellWidth: 18 }, 5: { cellWidth: 34 } },
    margin: { left: 12, right: 12, bottom: 16 },
  });
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const y = ((doc as any).lastAutoTable?.finalY ?? top) + 18;
  doc.setFontSize(9);
  doc.text(ascii(lh.controller_name || 'Controller of Examinations'), doc.internal.pageSize.getWidth() - 12, y, { align: 'right' });
  doc.setTextColor(...MUTED);
  doc.text('Signature & seal', doc.internal.pageSize.getWidth() - 12, y + 4.5, { align: 'right' });
  footers(doc);
  doc.save(`duty-list-${d.slot.date}-${d.slot.start_time.replace(':', '')}.pdf`);
}

export async function planExcel(d: PlanDetail) {
  const { downloadWorkbook } = await import('./excel');
  const paperById = new Map(d.slot.papers.map((p) => [p.id, p]));
  const roomById = new Map(d.rooms.map((r) => [r.id, r]));
  const rows: (string | number | null)[][] = [['Room', 'Seat', 'Roll number', 'Student name', 'Course', 'Semester', 'Subject']];
  for (const room of d.rooms) {
    const order = seatOrder(room);
    roomSeats(d, room.id)
      .sort((a, b) => (order.get(`${a.r}-${a.c}`)?.order ?? 0) - (order.get(`${b.r}-${b.c}`)?.order ?? 0))
      .forEach((s: SeatAssignment) => {
        const p = paperById.get(s.paper_id);
        rows.push([room.name, order.get(`${s.r}-${s.c}`)?.label ?? '', s.roll_no, s.name, p?.course_code ?? '', p?.semester ?? '', p?.subject ?? '']);
      });
  }
  const duties: (string | number | null)[][] = [['Room', 'Role', 'Teacher', 'Employee ID', 'Department', 'Email', 'Phone']];
  for (const x of d.duties) duties.push([x.room_id ? roomById.get(x.room_id)?.name ?? '' : 'Reserve', x.role, x.name, x.emp_code, x.department, x.email, x.phone]);
  await downloadWorkbook(`seating-plan-${d.slot.date}-${d.slot.start_time.replace(':', '')}.xlsx`, [
    { name: 'Seating', rows },
    { name: 'Invigilators', rows: duties },
  ]);
}

